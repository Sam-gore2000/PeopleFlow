#!/usr/bin/env bash
# =====================================================================
#  LionReach HRMS - one-command deploy for an Ubuntu/Debian VPS
#
#    chmod +x deploy.sh && ./deploy.sh
#
#  First run : asks for your domain (and optional Gmail), creates .env with
#              random passwords, builds and starts the app, creates the first
#              logins and prints them (also saved to credentials.txt).
#  Later runs: rebuilds and restarts with the latest code. Data and passwords stay.
# =====================================================================
set -euo pipefail
cd "$(dirname "$0")"

GREEN=$'\e[32m'; YELLOW=$'\e[33m'; RED=$'\e[31m'; BOLD=$'\e[1m'; RESET=$'\e[0m'
say()  { echo "${GREEN}==>${RESET} $*"; }
warn() { echo "${YELLOW}!!${RESET} $*"; }
die()  { echo "${RED}xx $*${RESET}" >&2; exit 1; }
SUDO=""; [ "$(id -u)" -ne 0 ] && command -v sudo >/dev/null && SUDO="sudo"

rand() { tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1"; }
# Easy-to-type but strong login password, e.g. Hrms-k3Xr9QmT2w
login_pass() { echo "Hrms-$(rand 10)"; }

# ---------- 1. Docker ----------
if ! command -v docker >/dev/null 2>&1; then
  warn "Docker is not installed."
  read -rp "Install Docker now? [Y/n] " yn
  [[ "${yn:-Y}" =~ ^[Nn] ]] && die "Docker is required. Install it and run ./deploy.sh again."
  curl -fsSL https://get.docker.com | $SUDO sh
  [ -n "$SUDO" ] && $SUDO usermod -aG docker "$USER" || true
fi
DOCKER="docker"
docker info >/dev/null 2>&1 || DOCKER="$SUDO docker"
$DOCKER compose version >/dev/null 2>&1 || die "Docker Compose v2 is missing (the 'docker compose' command). Re-run the Docker installer."
COMPOSE="$DOCKER compose"

# ---------- 2. Server checks ----------
MEM_MB=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
SWAP_MB=$(awk '/SwapTotal/ {print int($2/1024)}' /proc/meminfo)
if [ "$MEM_MB" -lt 1900 ] && [ "$SWAP_MB" -lt 1000 ]; then
  warn "This server has ${MEM_MB} MB RAM and no swap - building the app may run out of memory."
  read -rp "Create a 2 GB swap file (recommended)? [Y/n] " yn
  if [[ ! "${yn:-Y}" =~ ^[Nn] ]]; then
    $SUDO fallocate -l 2G /swapfile 2>/dev/null || $SUDO dd if=/dev/zero of=/swapfile bs=1M count=2048
    $SUDO chmod 600 /swapfile && $SUDO mkswap /swapfile >/dev/null && $SUDO swapon /swapfile
    grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' | $SUDO tee -a /etc/fstab >/dev/null
    say "Swap enabled."
  fi
fi

if command -v ufw >/dev/null 2>&1 && $SUDO ufw status 2>/dev/null | grep -q "Status: active"; then
  $SUDO ufw allow 80/tcp >/dev/null; $SUDO ufw allow 443/tcp >/dev/null; $SUDO ufw allow 443/udp >/dev/null
  say "Firewall: ports 80 and 443 opened."
fi

# ---------- 3. Settings (.env) - first run only ----------
FIRST_RUN=false
if [ ! -f .env ]; then
  FIRST_RUN=true
  echo
  echo "${BOLD}HRMS first-time setup${RESET}"
  echo "Your domain must already point to this server (DNS A record) for HTTPS."
  read -rp "Domain (e.g. hrm.lionreachmedia.com) - leave empty to use the server IP over HTTP: " DOMAIN
  DOMAIN="$(echo "${DOMAIN:-}" | sed -E 's#^https?://##; s#/.*$##')"
  if [ -n "$DOMAIN" ]; then
    SITE_ADDRESS="$DOMAIN"; PUBLIC_URL="https://$DOMAIN"; COOKIE_SECURE=true
  else
    IP="$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')"
    SITE_ADDRESS=":80"; PUBLIC_URL="http://$IP"; COOKIE_SECURE=false
    warn "No domain: the site will run on $PUBLIC_URL without HTTPS (OK for testing only)."
  fi

  read -rp "Admin email (for password resets, optional): " ADMIN_EMAIL
  echo "Gmail for forgot-password codes (optional - press Enter to skip, you can add it to .env later):"
  read -rp "  Gmail address: " SMTP_USER
  SMTP_PASS=""
  if [ -n "$SMTP_USER" ]; then read -rsp "  Gmail App Password (16 letters): " SMTP_PASS; echo; SMTP_PASS="${SMTP_PASS// /}"; fi

  MONGO_IMAGE="mongo:7"
  if ! grep -qw avx /proc/cpuinfo; then
    MONGO_IMAGE="mongo:4.4"
    warn "This CPU has no AVX support - using MongoDB 4.4."
  fi

  ADMIN_PASS="$(login_pass)"; MANAGER_PASS="$(login_pass)"; EMPLOYEE_PASS="$(login_pass)"

  umask 077
  cat > .env <<ENVFILE
# Generated by deploy.sh on $(date '+%Y-%m-%d %H:%M'). Keep this file private.

# ---- Website ----
SITE_ADDRESS=$SITE_ADDRESS
PUBLIC_URL=$PUBLIC_URL
COOKIE_SECURE=$COOKIE_SECURE

# ---- Database ----
MONGO_IMAGE=$MONGO_IMAGE
MONGO_ROOT_USER=hrms
MONGO_ROOT_PASSWORD=$(rand 32)

# ---- Login security ----
JWT_SECRET=$(rand 64)

# ---- First-start accounts (only created if they don't exist; changing these later changes nothing) ----
INITIAL_ADMIN_USERNAME=admin
INITIAL_ADMIN_PASSWORD=$ADMIN_PASS
INITIAL_ADMIN_EMAIL=$ADMIN_EMAIL
SEED_DEMO_ACCOUNTS=true
INITIAL_MANAGER_PASSWORD=$MANAGER_PASS
INITIAL_EMPLOYEE_PASSWORD=$EMPLOYEE_PASS

# ---- Email for forgot-password codes (Gmail + App Password) ----
SMTP_HOST=smtp.gmail.com
SMTP_PORT=465
SMTP_USER=$SMTP_USER
SMTP_PASS=$SMTP_PASS
MAIL_FROM="LionReach HRMS <${SMTP_USER:-noreply@example.com}>"

# ---- Company rules ----
APP_TIMEZONE=Asia/Kolkata
WEEKLY_OFF_DAYS=0,6
LEAVE_ACCRUAL_PER_MONTH=1.5
LEAVE_YEAR_START_MONTH=1
PROBATION_MONTHS=3
ENVFILE

  cat > credentials.txt <<CREDS
LionReach HRMS - first logins  (created $(date '+%Y-%m-%d %H:%M'))
Website: $PUBLIC_URL

Admin     username: admin    password: $ADMIN_PASS
Manager   username: MGR001   password: $MANAGER_PASS
Employee  username: EMP001   password: $EMPLOYEE_PASS

Change these passwords after the first login (My Profile -> Change Password).
Delete this file once you've stored the passwords somewhere safe:  rm credentials.txt
CREDS
  chmod 600 .env credentials.txt
  umask 022
  say "Settings saved to .env (random database password, JWT secret and login passwords)."
fi

# ---------- 4. Build and start ----------
say "Building and starting HRMS (the first build takes a few minutes)..."
$COMPOSE up -d --build --remove-orphans

# ---------- 5. Wait until healthy ----------
say "Waiting for the app to become ready..."
for _ in $(seq 1 60); do
  if $COMPOSE exec -T backend wget -qO- http://127.0.0.1:5000/api/health >/dev/null 2>&1; then READY=true; break; fi
  sleep 5
done
if [ "${READY:-false}" != true ]; then
  $COMPOSE ps
  echo; $COMPOSE logs --tail 40 backend || true
  die "The backend did not become ready in 5 minutes. See the log above (also: $COMPOSE logs backend)."
fi
$COMPOSE ps

# ---------- 6. Done ----------
PUBLIC_URL_NOW=$(grep '^PUBLIC_URL=' .env | cut -d= -f2-)
echo
echo "${GREEN}${BOLD}HRMS is running:${RESET} ${BOLD}$PUBLIC_URL_NOW${RESET}"
if [ "$FIRST_RUN" = true ] || [ -f credentials.txt ]; then
  echo; cat credentials.txt 2>/dev/null || true
fi
grep -q '^SMTP_PASS=$' .env && warn "Forgot-password emails are off until SMTP_USER/SMTP_PASS are set in .env (then run ./deploy.sh again)."
grep -q 'https://' <<<"$PUBLIC_URL_NOW" && echo "The HTTPS certificate is issued on the first visit (can take up to a minute)."
echo "Logs: $COMPOSE logs -f    |    Backup: sh scripts/backup.sh    |    Update: ./deploy.sh"
